"""mkfont.py -- tools/font.txt to src/font_data.c: 4bpp GBA tiles, one per
character code (ASCII 32..126, then the names below from 128).

    python3 tools/mkfont.py tools/font.txt src/font_data.c [sheet.png]

The optional PNG is a preview sheet of every glyph, to look at by eye.
"""
import struct
import sys
import zlib

NAMED = {'space': 32, 'male': 128, 'female': 129, 'e_acute': 130, 'ellipsis': 131,
         'cursor': 132, 'block': 133}
COUNT = 134


def parse(path):
    glyphs, name, rows = {}, None, []
    for line in open(path, encoding='utf-8'):
        line = line.rstrip('\n')
        if line.startswith('#') and name is None or not line:
            continue
        if line.startswith('= '):
            name, rows = line[2:], []
            continue
        rows.append(line)
        if len(rows) == 7:
            code = NAMED[name] if name in NAMED else ord(name)
            assert all(len(r) == 5 and set(r) <= {'#', '.'} for r in rows), name
            assert code not in glyphs, name
            glyphs[code] = rows
            name = None
    return glyphs


def tile(rows):
    """8x8 4bpp: glyph in columns 1..5, rows 0..6; colour 1 on, 0 off."""
    out = bytearray(32)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#':
                px = x + 1
                out[y * 4 + px // 2] |= 1 << (4 * (px & 1))
    return bytes(out)


def png(path, glyphs):
    cols, scale = 16, 3
    rows_n = (COUNT + cols - 1) // cols
    w, h = cols * 8 * scale, rows_n * 8 * scale
    img = [[40] * w for _ in range(h)]
    for code, rows in glyphs.items():
        gx, gy = code % cols * 8, code // cols * 8
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == '#':
                    for dy in range(scale):
                        for dx in range(scale):
                            img[(gy + y) * scale + dy][(gx + x + 1) * scale + dx] = 255
    raw = b''.join(b'\0' + bytes(v for v in row for _ in range(3)) for row in img)

    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xFFFFFFFF)
    open(path, 'wb').write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0)) +
                           chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def main(src, dst, sheet=None):
    glyphs = parse(src)
    missing = [c for c in range(33, 127) if c not in glyphs]
    assert not missing, 'no glyph for %r' % ''.join(map(chr, missing))
    with open(dst, 'w') as f:
        f.write('/* Generated by tools/mkfont.py from tools/font.txt: do not edit. */\n')
        f.write('#include <stdint.h>\n\nconst uint32_t font_tiles[%d * 8] = {\n' % COUNT)
        for code in range(COUNT):
            t = tile(glyphs[code]) if code in glyphs else bytes(32)
            words = struct.unpack('<8I', t)
            f.write('    ' + ', '.join('0x%08x' % w for w in words) + ',\n')
        f.write('};\n')
    if sheet:
        png(sheet, glyphs)


if __name__ == '__main__':
    main(*sys.argv[1:])
