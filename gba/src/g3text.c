/* g3text.c -- see g3text.h. The table is the games' own Western charmap
 * (pret's charmap.txt): 0x00 space, 0xA1.. digits, 0xBB.. capitals,
 * 0xD5.. small letters, 0xFF end of string. */
#include "g3text.h"

static const struct { uint8_t game, font; } punct[] = {
    {0x00, ' '}, {0x1B, FONT_E_ACUTE},
    {0xAB, '!'}, {0xAC, '?'}, {0xAD, '.'}, {0xAE, '-'}, {0xB0, FONT_ELLIPSIS},
    {0xB1, '"'}, {0xB2, '"'}, {0xB3, '\''}, {0xB4, '\''}, {0xB5, FONT_MALE},
    {0xB6, FONT_FEMALE}, {0xB7, '$'}, {0xB8, ','}, {0xBA, '/'}, {0xF0, ':'},
};

uint8_t g3_to_font(uint8_t c) {
    if (c >= 0xA1 && c <= 0xAA) return (uint8_t)('0' + c - 0xA1);
    if (c >= 0xBB && c <= 0xD4) return (uint8_t)('A' + c - 0xBB);
    if (c >= 0xD5 && c <= 0xEE) return (uint8_t)('a' + c - 0xD5);
    for (unsigned k = 0; k < sizeof punct / sizeof punct[0]; k++)
        if (punct[k].game == c) return punct[k].font;
    return '?';
}

uint8_t g3_from_font(uint8_t f) {
    if (f >= '0' && f <= '9') return (uint8_t)(0xA1 + f - '0');
    if (f >= 'A' && f <= 'Z') return (uint8_t)(0xBB + f - 'A');
    if (f >= 'a' && f <= 'z') return (uint8_t)(0xD5 + f - 'a');
    for (unsigned k = 0; k < sizeof punct / sizeof punct[0]; k++)
        if (punct[k].font == f) return punct[k].game;   /* the first: " and ' open */
    return 0;
}

int g3_decode(const uint8_t *s, int max, char *out) {
    int n = 0;
    for (; n < max && s[n] != G3_EOS; n++) out[n] = (char)g3_to_font(s[n]);
    out[n] = 0;
    return n;
}

